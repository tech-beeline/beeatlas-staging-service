-- ============================================================
-- V0030: Контекст паузы для типов, у которых он не выводится из канона (SFDM-4160)
-- e2e-plantuml показывает в паузе участников диаграммы, стороны вызовов и исходные
-- подписи — этих данных в канонической модели нет, они живут только в результате
-- transformer. Колонка возвращена как транспорт такого контекста; usecase по-прежнему
-- собирает контекст из канона (ADR-029).
-- ============================================================

ALTER TABLE staging.pipeline_runs
    ADD COLUMN IF NOT EXISTS draft_json text;

COMMENT ON COLUMN staging.pipeline_runs.draft_json IS
    'Контекст паузы, который нельзя собрать из канонической модели: участники диаграммы, '
    'стороны вызова и исходные подписи (e2e-plantuml). Заполняется transformer-ом, '
    'отдаётся в блоке result методов status/details';
